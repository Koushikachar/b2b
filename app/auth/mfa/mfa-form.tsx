"use client";

import { useEffect, useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { Button } from "@/components/ui/button";
import { InputOTP, InputOTPGroup, InputOTPSlot } from "@/components/ui/input-otp";
import { Skeleton } from "@/components/ui/skeleton";
import { createClient } from "@/lib/supabase/client";

type Mode =
  | { kind: "loading" }
  | { kind: "enroll"; factorId: string; qrCode: string; secret: string }
  | { kind: "verify"; factorId: string }
  | { kind: "error"; message: string };

/**
 * TOTP flow on Supabase Auth MFA. A verified factor → enter its code. None →
 * enroll a new one (stale unverified attempts are removed first so repeat
 * visits don't pile up factors), show its QR code, confirm with a code.
 * A successful code upgrades this session to aal2 (cookies are updated by the
 * browser client), then the admin page is reloaded.
 */
export function MfaForm({ next }: { next: string }) {
  const router = useRouter();
  const [mode, setMode] = useState<Mode>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [message, setMessage] = useState("");
  const [pending, startTransition] = useTransition();

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const supabase = createClient();
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (cancelled) return;
      if (error) {
        setMode({ kind: "error", message: "Couldn't load your authenticator. Refresh and try again." });
        return;
      }
      const verified = data.totp[0];
      if (verified) {
        setMode({ kind: "verify", factorId: verified.id });
        return;
      }
      for (const stale of data.all.filter((f) => f.factor_type === "totp" && f.status === "unverified")) {
        await supabase.auth.mfa.unenroll({ factorId: stale.id });
      }
      const enrolled = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: `Authenticator ${Date.now()}` });
      if (cancelled) return;
      if (enrolled.error || !enrolled.data) {
        setMode({ kind: "error", message: "Couldn't start authenticator set-up. Refresh and try again." });
        return;
      }
      setMode({
        kind: "enroll",
        factorId: enrolled.data.id,
        qrCode: enrolled.data.totp.qr_code,
        secret: enrolled.data.totp.secret,
      });
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  if (mode.kind === "loading") {
    return <Skeleton className="h-40 w-full" />;
  }
  if (mode.kind === "error") {
    return (
      <p role="alert" className="text-sm text-destructive">
        {mode.message}
      </p>
    );
  }

  const submit = (event: React.FormEvent) => {
    event.preventDefault();
    setMessage("");
    startTransition(async () => {
      const { error } = await createClient().auth.mfa.challengeAndVerify({ factorId: mode.factorId, code });
      if (error) {
        setCode("");
        setMessage("That code didn't work. Wait for a new one in the app and try again.");
        return;
      }
      router.replace(next);
      router.refresh();
    });
  };

  return (
    <form onSubmit={submit} className="flex flex-col gap-4">
      {mode.kind === "enroll" ? (
        <div className="flex flex-col items-center gap-3">
          <p className="text-sm text-muted-foreground">Scan this QR code with your authenticator app.</p>
          {/* SVG data URL generated by Supabase for this factor; not a remote image. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={mode.qrCode} alt="QR code for your authenticator app" width={176} height={176} className="size-44 rounded-md border border-border bg-white p-2" />
          <details className="w-full text-xs text-muted-foreground">
            <summary className="cursor-pointer">Can&apos;t scan? Enter this key instead</summary>
            <code className="mt-2 block break-all rounded-md bg-muted px-2 py-1.5 font-mono text-foreground">{mode.secret}</code>
          </details>
        </div>
      ) : (
        <p className="text-sm text-muted-foreground">Enter the 6-digit code from your authenticator app.</p>
      )}

      <InputOTP maxLength={6} value={code} onChange={setCode} autoFocus>
        <InputOTPGroup>
          {Array.from({ length: 6 }, (_, i) => (
            <InputOTPSlot key={i} index={i} />
          ))}
        </InputOTPGroup>
      </InputOTP>

      {message ? (
        <p role="alert" className="text-sm text-destructive">
          {message}
        </p>
      ) : null}

      <Button type="submit" disabled={pending || code.length !== 6}>
        {pending ? "Checking…" : mode.kind === "enroll" ? "Turn on and continue" : "Continue"}
      </Button>
    </form>
  );
}
